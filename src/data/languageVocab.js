/* Themed vocabulary for the language programme pages.
 *
 * Words are grouped the way they are taught — family, school, food — rather
 * than alphabetically, because a word learned beside five related words is
 * remembered and a word learned alone is not. Each list came across from the
 * standalone language pages and is kept here rather than inside a component so
 * a word can be corrected without touching any markup.
 *
 * `term` is the word itself, `sub` the line under it (a romanisation for the
 * Indian-script languages, a plain-English meaning for the English lists), and
 * `gloss` an example sentence where one exists. The pages that render these
 * pass the right `lang` so a browser picks a font that can draw the script.
 */

